namespace SprykerTest\Zed\ContentGui\Business;

use Codeception\Test\Unit;
use Generated\Shared\Transfer\CmsBlockGlossaryPlaceholderTransfer;
use Generated\Shared\Transfer\CmsBlockGlossaryPlaceholderTranslationTransfer;
use Generated\Shared\Transfer\CmsBlockGlossaryTransfer;
use Generated\Shared\Transfer\CmsGlossaryAttributesTransfer;
use Generated\Shared\Transfer\CmsGlossaryTransfer;
use Generated\Shared\Transfer\CmsPlaceholderTranslationTransfer;
use Spryker\Shared\Kernel\Store;
use Spryker\Zed\ContentGui\Business\ContentGuiFacadeInterface;
use Spryker\Zed\ContentGui\ContentGuiConfig;
use Spryker\Zed\ContentGui\ContentGuiDependencyProvider;
use SprykerTest\Zed\ContentGui\Plugin\ContentBannerContentGuiEditorPluginMock;
use SprykerTest\Zed\ContentGui\Plugin\ContentProductContentGuiEditorPluginMock;

/**
 * Auto-generated group annotations
 *
 * @group SprykerTest
 * @group Zed
 * @group ContentGui
 * @group Business
 * @group ContentGuiRichTextEditorContractTest
 * Add your own group annotations below this line
 */
class ContentGuiRichTextEditorContractTest extends Unit
{
    /**
     * The widget markup the Tiptap `contentItem` node renders; the Jest spec of the node renders and parses the same file.
     *
     * @var string
     */
    protected const FIXTURE_CONTENT_ITEM_BANNER = 'content-item-banner.html';

    /**
     * A copy of ContentGuiConfig::getEditorContentWidgetTemplate(), which the Jest spec uses as the widget template.
     *
     * @var string
     */
    protected const FIXTURE_WIDGET_TEMPLATE = 'content-item-template.html';

    /**
     * @var string
     */
    protected const TWIG_EXPRESSION_BANNER = "{{ content_banner('br-test', 'default') }}";

    /**
     * @var string
     */
    protected const PATTERN_CONTENT_ID = '/data-id="\d+"/';

    /**
     * @var string
     */
    protected const FIXTURE_CONTENT_ID = 'data-id="1"';

    /**
     * @var \SprykerTest\Zed\ContentGui\ContentGuiBusinessTester
     */
    protected $tester;

    protected function setUp(): void
    {
        parent::setUp();

        $this->tester->setDependency(ContentGuiDependencyProvider::PLUGINS_CONTENT_EDITOR, [
            new ContentBannerContentGuiEditorPluginMock(),
            new ContentProductContentGuiEditorPluginMock(),
        ]);
        $this->tester->createBannerContentItem();
    }

    public function testWidgetTemplateFixtureMatchesTheConfiguredTemplate(): void
    {
        // Act
        $widgetTemplate = (new ContentGuiConfig())->getEditorContentWidgetTemplate();

        // Assert
        $this->assertSame($this->readFixture(static::FIXTURE_WIDGET_TEMPLATE), $widgetTemplate);
    }

    public function testEditorWidgetInCmsGlossaryIsSavedAsTwigExpression(): void
    {
        // Arrange
        $cmsGlossaryTransfer = $this->createCmsGlossaryTransfer($this->wrapInParagraphs($this->readFixture(static::FIXTURE_CONTENT_ITEM_BANNER)));

        // Act
        $cmsGlossaryTransfer = $this->getFacade()->convertCmsGlossaryHtmlToTwigExpressions($cmsGlossaryTransfer);

        // Assert
        $this->assertSame(
            $this->wrapInParagraphs(static::TWIG_EXPRESSION_BANNER),
            $cmsGlossaryTransfer->getGlossaryAttributes()->offsetGet(0)->getTranslations()->offsetGet(0)->getTranslation(),
        );
    }

    public function testEditorWidgetInCmsBlockGlossaryIsSavedAsTwigExpression(): void
    {
        // Arrange
        $cmsBlockGlossaryTransfer = $this->createCmsBlockGlossaryTransfer($this->wrapInParagraphs($this->readFixture(static::FIXTURE_CONTENT_ITEM_BANNER)));

        // Act
        $cmsBlockGlossaryTransfer = $this->getFacade()->convertCmsBlockGlossaryHtmlToTwigExpressions($cmsBlockGlossaryTransfer);

        // Assert
        $this->assertSame(
            $this->wrapInParagraphs(static::TWIG_EXPRESSION_BANNER),
            $cmsBlockGlossaryTransfer->getGlossaryPlaceholders()->offsetGet(0)->getTranslations()->offsetGet(0)->getTranslation(),
        );
    }

    /**
     * The content id is generated by the database, so it is normalized to the fixture's value before comparing.
     */
    public function testStoredTwigExpressionIsLoadedAsTheEditorWidget(): void
    {
        // Arrange
        if (!getenv('SPRYKER_DYNAMIC_STORE_MODE')) {
            Store::getInstance()->setCurrentLocale('en_US');
        }

        $cmsGlossaryTransfer = $this->createCmsGlossaryTransfer(static::TWIG_EXPRESSION_BANNER);

        // Act
        $cmsGlossaryTransfer = $this->getFacade()->convertCmsGlossaryTwigExpressionsToHtml($cmsGlossaryTransfer);

        // Assert
        $translation = (string)$cmsGlossaryTransfer->getGlossaryAttributes()->offsetGet(0)->getTranslations()->offsetGet(0)->getTranslation();
        $this->assertSame(
            $this->readFixture(static::FIXTURE_CONTENT_ITEM_BANNER),
            preg_replace(static::PATTERN_CONTENT_ID, static::FIXTURE_CONTENT_ID, $translation),
        );
    }

    protected function getFacade(): ContentGuiFacadeInterface
    {
        /** @var \Spryker\Zed\ContentGui\Business\ContentGuiFacadeInterface $contentGuiFacade */
        $contentGuiFacade = $this->tester->getFacade();

        return $contentGuiFacade;
    }

    protected function readFixture(string $fileName): string
    {
        return trim((string)file_get_contents(codecept_data_dir('rich-text-editor/' . $fileName)));
    }

    protected function wrapInParagraphs(string $html): string
    {
        return sprintf('<p>Intro</p>%s<p>Outro</p>', $html);
    }

    protected function createCmsGlossaryTransfer(string $translation): CmsGlossaryTransfer
    {
        $cmsGlossaryAttributesTransfer = (new CmsGlossaryAttributesTransfer())
            ->addTranslation((new CmsPlaceholderTranslationTransfer())->setTranslation($translation));

        return (new CmsGlossaryTransfer())->addGlossaryAttribute($cmsGlossaryAttributesTransfer);
    }

    protected function createCmsBlockGlossaryTransfer(string $translation): CmsBlockGlossaryTransfer
    {
        $cmsBlockGlossaryPlaceholderTransfer = (new CmsBlockGlossaryPlaceholderTransfer())
            ->addTranslation((new CmsBlockGlossaryPlaceholderTranslationTransfer())->setTranslation($translation));

        return (new CmsBlockGlossaryTransfer())->addGlossaryPlaceholder($cmsBlockGlossaryPlaceholderTransfer);
    }
}
